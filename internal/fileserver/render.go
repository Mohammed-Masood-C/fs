//go:embed assets
var assets embed.FS

// templates holds the parsed pages and the stylesheet and script that are
// inlined into them, so that no URL inside the served folder is reserved.
type templates struct {
	listing *template.Template
	errPage *template.Template
	css     template.CSS
	js      template.JS
}

func loadTemplates() (*templates, error) {
	css, err := assets.ReadFile("assets/listing.css")
	if err != nil {
		return nil, err
	}
	js, err := assets.ReadFile("assets/listing.js")
	if err != nil {
		return nil, err
	}
	listing, err := template.ParseFS(assets, "assets/listing.html")
	if err != nil {
		return nil, fmt.Errorf("parse explorer template: %w", err)
	}
	errPage, err := template.ParseFS(assets, "assets/error.html")
	if err != nil {
		return nil, fmt.Errorf("parse error template: %w", err)
	}
	// html/template escapes lazily on first use; render both pages once so a
	// broken template fails at startup instead of on every request.
	if err := listing.Execute(io.Discard, listingView{}); err != nil {
		return nil, fmt.Errorf("check explorer template: %w", err)
	}
	if err := errPage.Execute(io.Discard, errorView{}); err != nil {
		return nil, fmt.Errorf("check error template: %w", err)
	}
	return &templates{
		listing: listing,
		errPage: errPage,
		css:     template.CSS(css),
		js:      template.JS(js),
	}, nil
}

// newNonce returns a fresh Content-Security-Policy nonce.
func newNonce() string { return rand.Text() }

// contentSecurityPolicy only allows the inline style and script carrying
// nonce, so a crafted file name can never inject markup that runs.
func contentSecurityPolicy(nonce string) string {
	return "default-src 'none'; img-src 'self' data:; " +
		"style-src 'nonce-" + nonce + "'; script-src 'nonce-" + nonce + "'; " +
		"base-uri 'none'; form-action 'none'; frame-ancestors 'self'"
}

// writeHTML renders a page generated by fs itself.
func (h *Handler) writeHTML(w http.ResponseWriter, r *http.Request, status int, tmpl *template.Template, data any, nonce string) {
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		h.logger.Error("render page", "template", tmpl.Name(), "err", err)
		http.Error(w, http.StatusText(http.StatusInternalServerError), http.StatusInternalServerError)
		return
	}
	hdr := w.Header()
	hdr.Set("Content-Type", "text/html; charset=utf-8")
	hdr.Set("Content-Security-Policy", contentSecurityPolicy(nonce))
	writeBody(w, r, status, buf.Bytes())
}

func (h *Handler) writeJSON(w http.ResponseWriter, r *http.Request, v any) {
	body, err := json.Marshal(v)
	if err != nil {
		h.logger.Error("encode json", "err", err)
		http.Error(w, http.StatusText(http.StatusInternalServerError), http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	writeBody(w, r, http.StatusOK, body)
}

// gzipMinSize is the smallest body worth compressing.
const gzipMinSize = 1024

var gzipWriters = sync.Pool{
	New: func() any { return gzip.NewWriter(io.Discard) },
}

// writeBody writes a generated response, gzip-compressed when the client
// accepts it. Files are never compressed here, which keeps Range requests
// and sendfile working for them.
func writeBody(w http.ResponseWriter, r *http.Request, status int, body []byte) {
	hdr := w.Header()
	hdr.Add("Vary", "Accept-Encoding")
	if len(body) >= gzipMinSize && acceptsGzip(r) {
		var buf bytes.Buffer
		zw := gzipWriters.Get().(*gzip.Writer)
		zw.Reset(&buf)
		zw.Write(body) // writes to a bytes.Buffer cannot fail
		zw.Close()
		zw.Reset(io.Discard)
		gzipWriters.Put(zw)
		body = buf.Bytes()
		hdr.Set("Content-Encoding", "gzip")
	}
	hdr.Set("Content-Length", strconv.Itoa(len(body)))
	w.WriteHeader(status)
	if r.Method != http.MethodHead {
		w.Write(body)
	}
}

// acceptsGzip reports whether the Accept-Encoding header allows gzip.
func acceptsGzip(r *http.Request) bool {
	for _, header := range r.Header.Values("Accept-Encoding") {
		for _, part := range strings.Split(header, ",") {
			coding, params, _ := strings.Cut(part, ";")
			if !strings.EqualFold(strings.TrimSpace(coding), "gzip") {
				continue
			}
			// "gzip;q=0" explicitly refuses gzip.
			if q, ok := strings.CutPrefix(strings.TrimSpace(params), "q="); ok {
				if v, err := strconv.ParseFloat(q, 64); err == nil && v == 0 {
					return false
				}
			}
			return true
		}
	}
	return false
}

// errorView is the data of the error page template.
type errorView struct {
	Status  int
	Title   string
	Message string
	Nonce   string
	CSS     template.CSS
}

var errorMessages = map[int]string{
	http.StatusBadRequest:          "The request could not be understood.",
	http.StatusForbidden:           "You do not have permission to view this page.",
	http.StatusNotFound:            "The file or folder you are looking for does not exist.",
	http.StatusInternalServerError: "The server ran into a problem while handling the request.",
}

// serveError writes an HTML error page.
func (h *Handler) serveError(w http.ResponseWriter, r *http.Request, status int) {
	nonce := newNonce()
	w.Header().Set("Cache-Control", "no-store")
	h.writeHTML(w, r, status, h.tmpl.errPage, errorView{
		Status:  status,
		Title:   http.StatusText(status),
		Message: errorMessages[status],
		Nonce:   nonce,
		CSS:     h.tmpl.css,
	}, nonce)
}
